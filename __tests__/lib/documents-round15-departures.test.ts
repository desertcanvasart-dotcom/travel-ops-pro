// A query builder that records every call and resolves to no rows.
const calls: Array<[string, unknown[]]> = []
function builder(): unknown {
  const target = {
    then: (resolve: (v: unknown) => unknown) => resolve({ data: [], error: null }),
  }
  return new Proxy(target, {
    get(t, prop: string) {
      if (prop === 'then') return t.then
      return (...args: unknown[]) => {
        calls.push([prop, args])
        return builder()
      }
    },
  })
}

vi.mock('@supabase/supabase-js', () => ({ createClient: () => ({ from: (t: string) => { calls.push(['from', [t]]); return builder() } }) }))
vi.mock('@/lib/auth/current-org', () => ({
  getCurrentOrgId: async () => 'org-A',
  noOrgResponse: () => new Response(JSON.stringify({ success: false }), { status: 403 }),
}))
vi.mock('@/lib/org-identity', () => ({ orgIdentity: async () => ({ name: 'Nile <b>Journeys</b>' }) }))
vi.mock('@/lib/org-rate-currency', () => ({ getOrgRateCurrency: async () => 'JPY' }))
vi.mock('@/lib/pdf-fonts-server', () => ({ getJapaneseFontFace: async () => '' }))
vi.mock('@/lib/i18n/server-messages', () => ({
  getServerLocale: async () => 'en',
  lookupServerMessage: (_l: string, key: string, vars?: Record<string, string>) => {
    if (key.endsWith('generatedBy')) return `Generated by ${vars?.company}`
    if (key.endsWith('dayN')) return 'Day {n}'
    if (key.endsWith('perPersonHint')) return '{rate} pp × {pax}'
    return key.split('.').pop()
  },
}))

