#!/usr/bin/env node
// ============================================
// Generate the Japanese placeholder-label migration from its data file
// ============================================
// Source: migrations/data/template-placeholders.ja.mjs (hand-written).
// Reference: migrations/data/template-placeholders.en.json (159 rows, 2026-08-22).
//   node scripts/build-template-placeholders-ja.mjs > migrations/20260823_template_placeholders_ja.sql
// ============================================
import { JA_PLACEHOLDERS } from '../migrations/data/template-placeholders.ja.mjs'
import fs from 'node:fs'
const EN = JSON.parse(fs.readFileSync(new URL('../migrations/data/template-placeholders.en.json', import.meta.url), 'utf8'))
const q = (s) => s == null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`
const out = [`-- ============================================
-- Japanese labels for the template placeholder picker
-- ============================================
-- GENERATED by scripts/build-template-placeholders-ja.mjs from
-- migrations/data/template-placeholders.ja.mjs — edit the data file, not this.
-- Adds display_name_ja / description_ja / example_value_ja next to the
-- English columns (which stay the fallback), then fills them. Idempotent.
-- ============================================

ALTER TABLE public.template_placeholders ADD COLUMN IF NOT EXISTS display_name_ja TEXT;
ALTER TABLE public.template_placeholders ADD COLUMN IF NOT EXISTS description_ja TEXT;
ALTER TABLE public.template_placeholders ADD COLUMN IF NOT EXISTS example_value_ja TEXT;
`]
let n = 0
for (const en of EN) {
  const ja = JA_PLACEHOLDERS[en.placeholder]
  if (!ja) throw new Error(`No Japanese label for ${en.placeholder}`)
  n++
  out.push(`UPDATE public.template_placeholders SET display_name_ja = ${q(ja.display_name)}, description_ja = ${q(ja.description)}, example_value_ja = ${q(ja.example_value)} WHERE placeholder = ${q(en.placeholder)};`)
}
const extra = Object.keys(JA_PLACEHOLDERS).filter(k => !EN.some(e => e.placeholder === k))
if (extra.length) throw new Error(`Japanese labels for unknown placeholders: ${extra.join(', ')}`)
out.push(`-- ${n} placeholders.`)
process.stdout.write(out.join('\n') + '\n')
