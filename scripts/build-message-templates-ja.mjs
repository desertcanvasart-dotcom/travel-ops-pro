#!/usr/bin/env node
// ============================================
// Generate the Japanese message-template seed migration from its data file
// ============================================
// Source of truth: migrations/data/message-templates.ja.mjs (hand-written
// Japanese). Reference: migrations/data/message-templates.en.json (the 42
// English rows as of 2026-08-22). The migration copies every non-text field
// (category, subcategory, placeholders, is_active) from the English twin at
// apply time, so the pair can never drift in metadata, and upserts on
// (name, channel, language) so re-running replaces rather than duplicates.
//
//   node scripts/build-message-templates-ja.mjs > migrations/20260823_message_templates_ja.sql
// ============================================
import { JA_TEMPLATES } from '../migrations/data/message-templates.ja.mjs'
import fs from 'node:fs'

const EN = JSON.parse(fs.readFileSync(new URL('../migrations/data/message-templates.en.json', import.meta.url), 'utf8'))
const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const placeholders = (s) => [...new Set([...String(s || '').matchAll(/\{\{\s*([A-Za-z0-9_]+)\s*\}\}/g)].map(m => m[1]))].sort()

const lines = [`-- ============================================
-- Japanese versions of the customer and internal message templates
-- ============================================
-- GENERATED by scripts/build-message-templates-ja.mjs from
-- migrations/data/message-templates.ja.mjs — edit the data file, not this.
--
-- Operator decision 2026-08-22: Japanese for everything sent to travellers
-- (customer) and for the team's own notes (internal). Supplier, partner and
-- B2B templates go to Egyptian hotels, guides, transport companies and agents,
-- who read English, and stay English.
--
-- Each row copies category / subcategory / placeholders / is_active from its
-- English twin (same name + channel) at apply time, so the pair cannot drift.
-- Every {{Placeholder}} in the Japanese text is identical to the English
-- twin's set — enforced by __tests__/lib/message-templates-ja.test.ts.
-- Upserts on (name, channel, language): safe to re-run.
-- ============================================
`]
let n = 0
for (const t of JA_TEMPLATES) {
  const en = EN.find(e => e.name === t.name && e.channel === t.channel)
  if (!en) throw new Error(`No English twin for ${t.name} | ${t.channel}`)
  const a = placeholders(en.body + ' ' + (en.subject || '')), b = placeholders(t.body + ' ' + (t.subject || ''))
  if (JSON.stringify(a) !== JSON.stringify(b)) throw new Error(`Placeholder mismatch for ${t.name} | ${t.channel}\n  en: ${a.join(',')}\n  ja: ${b.join(',')}`)
  n++
  lines.push(`INSERT INTO public.message_templates (id, name, description, category, subcategory, channel, subject, body, placeholders, is_active, language, created_at, updated_at)
SELECT gen_random_uuid(), e.name, ${q(t.description)}, e.category, e.subcategory, e.channel, ${t.subject ? q(t.subject) : 'NULL'}, ${q(t.body)}, e.placeholders, e.is_active, 'ja', NOW(), NOW()
FROM public.message_templates e
WHERE e.name = ${q(t.name)} AND e.channel = ${q(t.channel)} AND e.language = 'en'
ON CONFLICT (name, channel, language) DO UPDATE
  SET description = EXCLUDED.description, subject = EXCLUDED.subject, body = EXCLUDED.body,
      category = EXCLUDED.category, subcategory = EXCLUDED.subcategory, placeholders = EXCLUDED.placeholders, updated_at = NOW();
`)
}
lines.push(`-- ${n} templates.`)
process.stdout.write(lines.join('\n'))
